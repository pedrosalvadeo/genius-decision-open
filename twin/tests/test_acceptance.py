    def test_idempotence_concurrent_acceptance_and_restore_are_append_only(self):
        cid, first = self.create()
        proposal = self.relay(cid)
        # Two writers truly race on the same immutable base. Exactly one commits.
        def accept(key):
            with self.app.test_client() as client:
                response = client.post(f"/api/proposals/{proposal['id']}/accept", json=self.acceptance(1, key))
                return response.status_code, response.get_json()
        with ThreadPoolExecutor(max_workers=2) as pool:
            outcomes = list(pool.map(accept, ["concurrent-001", "concurrent-002"]))
        self.assertEqual(sorted(code for code, _ in outcomes), [200, 409])
        winning_index = next(i for i, (code, _) in enumerate(outcomes) if code == 200)
        winning_key = ["concurrent-001", "concurrent-002"][winning_index]
        repeated = self.post(f"/api/proposals/{proposal['id']}/accept", self.acceptance(1, winning_key))
        self.assertEqual(repeated, outcomes[winning_index][1])
        changed_payload = self.acceptance(2, winning_key)
        error = self.post(f"/api/proposals/{proposal['id']}/accept", changed_payload, 409)
        self.assertEqual(error["error"]["code"], "idempotency_conflict")
        undo = self.post(f"/api/cases/{cid}/proposals", {"base_version": 2, "kind": "restore",
                         "text": "Restaurar el modelo inicial.", "structured": {"version": 1}}, 201)["proposal"]
        restored = self.post(f"/api/proposals/{undo['id']}/accept", self.acceptance(2, "restore-0001"))
        self.assertEqual(restored["version"]["version"], 3)
        self.assertEqual(restored["version"]["model"], first["version"]["model"])
        state = self.client.get(f"/api/cases/{cid}").get_json()
        self.assertEqual([v["version"] for v in state["versions"]], [1, 2, 3])
        self.assertEqual(state["versions"][0], first["version"])

