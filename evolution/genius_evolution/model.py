"""Exact, bounded program synthesis; no model provider and no arbitrary code input."""
from fractions import Fraction
import json
import os
import subprocess
import sys

LIMIT = 1_000_000


def require(condition, code):
    if not condition:
        raise ValueError(code)


def validate(model):
    require(type(model) is dict and set(model) == {'lag', 'a', 'b', 'denominator'}, 'MODEL_FIELDS')
    require(all(type(v) is int for v in model.values()), 'MODEL_INTEGERS')
    require(1 <= model['lag'] <= 3 and 1 <= model['denominator'] <= LIMIT, 'MODEL_BOUNDS')
    require(abs(model['a']) <= LIMIT and abs(model['b']) <= 10 * LIMIT, 'MODEL_BOUNDS')


def predict(model, history, baseline):
    validate(model)
    if len(history) < model['lag']:
        return baseline
    return max(0, min(LIMIT, (model['a'] * history[-model['lag']] + model['b']) // model['denominator']))


def render(model):
    validate(model)
    return ('# Generated by Genius evolution v1; review the bound proposal before use.\n'
            '# Domain: integer observations in [0, 1000000]; no side effects.\n'
            'def predict(history, baseline):\n'
            f'    if len(history) < {model["lag"]}:\n'
            '        return baseline\n'
            f'    return max(0, min(1000000, ({model["a"]} * history[-{model["lag"]}] + '
            f'{model["b"]}) // {model["denominator"]}))\n')


def loss(predictions, values, objective):
    under = [max(0, v - p) for p, v in zip(predictions, values)]
    over = [max(0, p - v) for p, v in zip(predictions, values)]
    require(len(predictions) == len(values) > 0, 'SCORE_COUNT')
    return dict(count=len(values), weighted_loss=sum(under) * objective['under_cost'] +
                sum(over) * objective['over_cost'], absolute_error_sum=sum(under) + sum(over),
                max_underprediction=max(under), max_overprediction=max(over))


def discover(cases, objective):
    """Fit exact affine programs at three lags, select ONLY by training loss.

    Coefficients are fitted by least squares; the frozen weighted error selects
    among those fitted programs. This is not a claim of optimal weighted fitting.
    """
    candidates = []
    for lag in (1, 2, 3):
        pairs = [(v[i-lag], v[i]) for case in cases for v in [case['values']]
                 for i in range(max(lag, objective['warmup_count']), len(v))]
        n = len(pairs)
        sx, sy = sum(x for x, _ in pairs), sum(y for _, y in pairs)
        denominator = n * sum(x*x for x, _ in pairs) - sx*sx
        slope = Fraction(n * sum(x*y for x, y in pairs) - sx*sy, denominator) if denominator else Fraction(0)
        intercept = Fraction(sy, n) - slope * Fraction(sx, n)
        import math
        d = math.lcm(slope.denominator, intercept.denominator)
        model = dict(lag=lag, a=int(slope*d), b=int(intercept*d), denominator=d)
        try:
            validate(model)
        except ValueError:
            continue
        values, predictions = [], []
        for case in cases:
            v = case['values']
            for i in range(objective['warmup_count'], len(v)):
                values.append(v[i]); predictions.append(predict(model, v[:i], objective['baseline']))
        score = loss(predictions, values, objective)
        candidates.append(dict(model=model, training=score))
    require(candidates, 'NO_BOUNDED_CANDIDATE')
    chosen = min(candidates, key=lambda c: (c['training']['weighted_loss'], c['model']['lag'],
                                          abs(c['model']['a']) + abs(c['model']['b']), c['model']['denominator']))
    return chosen, candidates


# Fixed runner, not supplied by a request. Generated code has no imports or I/O;
# only the exact bytes rendered above are accepted. CI adds OS network isolation.
WORKER = '''import json, resource, sys
resource.setrlimit(resource.RLIMIT_CPU, (3, 3))
resource.setrlimit(resource.RLIMIT_AS, (128*1024*1024, 128*1024*1024))
resource.setrlimit(resource.RLIMIT_FSIZE, (1024*1024, 1024*1024))
resource.setrlimit(resource.RLIMIT_NOFILE, (16, 16))
p = json.loads(sys.stdin.read(1024*1024))
ns = {"__builtins__": {"len": len, "min": min, "max": max}}
exec(compile(p["source"], "<generated-strategy>", "exec"), ns)
results = [[ns["predict"](values[:i], p["baseline"]) for i in range(len(values))] for values in p["cases"]]
print(json.dumps(results, separators=(",", ":")))
'''


def execute(source, model, cases, baseline):
    require(source == render(model), 'UNAPPROVED_SOURCE')
    require(type(baseline) is int and 0 <= baseline <= LIMIT, 'BASELINE')
    require(1 <= len(cases) <= 12, 'EXECUTION_CASE_LIMIT')
    require(all(6 <= len(c['values']) <= 128 and all(type(v) is int and 0 <= v <= LIMIT
                for v in c['values']) for c in cases), 'EXECUTION_DATA_LIMIT')
    payload = json.dumps(dict(source=source, baseline=baseline, cases=[c['values'] for c in cases]))
    require(len(payload.encode()) <= 64 * 1024, 'EXECUTION_INPUT_LIMIT')
    result = subprocess.run([sys.executable, '-I', '-S', '-c', WORKER], input=payload,
                            text=True, capture_output=True, timeout=5,
                            env={'PATH': os.defpath, 'LANG': 'C.UTF-8', 'PYTHONDONTWRITEBYTECODE': '1'})
    require(result.returncode == 0 and len(result.stdout) <= 64 * 1024, 'CANDIDATE_EXECUTION_FAILED')
    actual = json.loads(result.stdout)
    expected = [[predict(model, c['values'][:i], baseline) for i in range(len(c['values']))] for c in cases]
    require(actual == expected, 'CANDIDATE_REFERENCE_DISAGREEMENT')
    return actual
